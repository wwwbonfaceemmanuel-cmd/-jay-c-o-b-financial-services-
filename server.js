/* =====================================================================
   JAY C O B FINANCIAL SERVICES — web server for Railway
   ---------------------------------------------------------------------
   Zero dependencies. Serves the static site from this repository and
   answers /env.js with the Supabase connection details taken from the
   environment, so the anon key is configured in Railway rather than
   committed to Git.

   Environment variables
     SUPABASE_URL        https://<project>.supabase.co
     SUPABASE_ANON_KEY   public anon key (never the service-role key)
     PORT                provided by Railway
     SUPABASE_PROXY      "1" to forward /sb/* to SUPABASE_URL. Only for
                         local previews, where the browser cannot reach
                         the development stand-in directly. Never set it
                         in production.

   Health check: GET /healthz
   ===================================================================== */
"use strict";

const http = require("http");
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const PORT = Number(process.env.PORT || 8080);
const HOST = "0.0.0.0";

const PROXY = process.env.SUPABASE_PROXY === "1" && !!process.env.SUPABASE_URL;
const PROXY_PREFIX = "/sb";

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".png": "image/png",
  ".webp": "image/webp",
  ".gif": "image/gif",
  ".ico": "image/x-icon",
  ".txt": "text/plain; charset=utf-8",
  ".xml": "application/xml; charset=utf-8",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".pdf": "application/pdf"
};

const SECURITY_HEADERS = {
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "X-Frame-Options": "SAMEORIGIN"
};

/* A preview pane embeds the site in a frame it does not control, so the
   frame guard is relaxed only for that development mode. */
if (PROXY) delete SECURITY_HEADERS["X-Frame-Options"];

if (PROXY) {
  const CSP = "frame-ancestors *";
  SECURITY_HEADERS["Content-Security-Policy"] = CSP;
}

function envScript() {
  const url = process.env.SUPABASE_URL || "";
  const key = process.env.SUPABASE_ANON_KEY || "";
  if (PROXY) {
    /* The browser talks to this server, which forwards to Supabase. The
       address therefore has to be resolved in the browser, not here. */
    return (
      "/* generated by server.js — do not edit */\n" +
      "window.__JCOB_ENV__ = " + JSON.stringify({ supabaseAnonKey: key }) + ";\n" +
      "window.__JCOB_ENV__.supabaseUrl = window.location.origin + " + JSON.stringify(PROXY_PREFIX) + ";\n"
    );
  }
  return (
    "/* generated by server.js — do not edit */\n" +
    "window.__JCOB_ENV__ = " +
    JSON.stringify({ supabaseUrl: url, supabaseAnonKey: key }) +
    ";\n"
  );
}

/* Forward one request to Supabase, keeping method, headers and body. */
function proxyToSupabase(req, res) {
  const target = new URL(process.env.SUPABASE_URL);
  const pathAndQuery = req.url.replace(/^\/sb/, "") || "/";
  const lib = target.protocol === "https:" ? require("https") : require("http");
  const headers = Object.assign({}, req.headers);
  headers.host = target.host;
  delete headers.connection;

  const upstream = lib.request({
    protocol: target.protocol,
    hostname: target.hostname,
    port: target.port || (target.protocol === "https:" ? 443 : 80),
    method: req.method,
    path: (target.pathname.replace(/\/$/, "") || "") + pathAndQuery,
    headers: headers
  }, (up) => {
    res.writeHead(up.statusCode || 502, up.headers);
    up.pipe(res);
  });
  upstream.on("error", () => {
    res.writeHead(502, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ message: "Supabase could not be reached" }));
  });
  req.pipe(upstream);
}

function send(res, status, body, headers) {
  res.writeHead(status, Object.assign({}, SECURITY_HEADERS, headers || {}));
  res.end(body);
}

function serveFile(res, filePath, status) {
  fs.stat(filePath, (err, stat) => {
    if (err || !stat.isFile()) return send(res, 404, "Not found", { "Content-Type": "text/plain" });
    const ext = path.extname(filePath).toLowerCase();
    const type = TYPES[ext] || "application/octet-stream";
    const cache = ext === ".html" || ext === ".js"
      ? "no-cache"
      : "public, max-age=86400";
    res.writeHead(status || 200, Object.assign({}, SECURITY_HEADERS, {
      "Content-Type": type,
      "Content-Length": stat.size,
      "Cache-Control": cache
    }));
    fs.createReadStream(filePath).pipe(res);
  });
}

const server = http.createServer((req, res) => {
  const url = new URL(req.url, "http://localhost");
  let pathname = decodeURIComponent(url.pathname);

  if (pathname === "/healthz") {
    return send(res, 200, JSON.stringify({
      status: "ok",
      cloud: !!(process.env.SUPABASE_URL && process.env.SUPABASE_ANON_KEY),
      time: new Date().toISOString()
    }), { "Content-Type": "application/json" });
  }

  if (pathname === "/env.js") {
    return send(res, 200, envScript(), {
      "Content-Type": "text/javascript; charset=utf-8",
      "Cache-Control": "no-store"
    });
  }

  if (PROXY && pathname.startsWith(PROXY_PREFIX + "/")) {
    return proxyToSupabase(req, res);
  }

  if (pathname === "/") pathname = "/index.html";

  /* resolve inside the repository only */
  const filePath = path.join(ROOT, path.normalize(pathname).replace(/^(\.\.[/\\])+/, ""));
  if (!filePath.startsWith(ROOT)) return send(res, 403, "Forbidden", { "Content-Type": "text/plain" });

  fs.stat(filePath, (err, stat) => {
    if (!err && stat.isDirectory()) return serveFile(res, path.join(filePath, "index.html"));
    if (!err && stat.isFile()) return serveFile(res, filePath);
    /* unknown page: the branded 404, with a real 404 status */
    return serveFile(res, path.join(ROOT, "404.html"), 404);
  });
});

server.listen(PORT, HOST, () => {
  console.log("JAY C O B site listening on http://" + HOST + ":" + PORT);
  console.log("Supabase: " + (process.env.SUPABASE_URL ? "configured" : "not configured (offline mode)"));
});
